export const STRINGS: Record<Lang, Strings> = { en, es, ja, ko, vi, fil };

export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
    const strings = STRINGS[lang];
    return (key, vars) => strings[key].replace(/\{(\w+)\}/g, (whole, name: string) => (vars && name in vars ? String(vars[name]) : whole));
}

const isLang = (code: string): code is Lang => LANGS.some((l) => l.code === code);

/** The language to start in: the one chosen before, else the browser's, else English.
 *  `tl` is the browser code for Tagalog, which the map carries as Filipino. */
export function pickLang(saved: string | null, browser: readonly string[]): Lang {
    if (saved && isLang(saved)) return saved;
    for (const tag of browser) {
        const code = tag.toLowerCase().split('-')[0];
        if (code === 'tl') return 'fil';
        if (isLang(code)) return code;
    }
    return 'en';
}
